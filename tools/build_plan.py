def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr(); shd = OxmlElement('w:shd'); shd.set(qn('w:fill'), fill); tcPr.append(shd)

def set_cell_margins(cell, top=80, start=120, bottom=80, end=120):
    tc = cell._tc; tcPr = tc.get_or_add_tcPr(); tcMar = tcPr.first_child_found_in('w:tcMar')
    if tcMar is None: tcMar = OxmlElement('w:tcMar'); tcPr.append(tcMar)
    for m, v in [('top', top), ('start', start), ('bottom', bottom), ('end', end)]:
        node = tcMar.find(qn(f'w:{m}'))
        if node is None: node = OxmlElement(f'w:{m}'); tcMar.append(node)
        node.set(qn('w:w'), str(v)); node.set(qn('w:type'), 'dxa')

def set_width(cell, width):
    tcPr = cell._tc.get_or_add_tcPr(); tcW = tcPr.find(qn('w:tcW'))
    if tcW is None: tcW = OxmlElement('w:tcW'); tcPr.append(tcW)
    tcW.set(qn('w:w'), str(width)); tcW.set(qn('w:type'), 'dxa')

def fixed_table(table, widths):
    table.autofit = False; table.alignment = WD_TABLE_ALIGNMENT.LEFT
    tblPr = table._tbl.tblPr; tblW = tblPr.first_child_found_in('w:tblW'); tblW.set(qn('w:w'), '9360'); tblW.set(qn('w:type'), 'dxa')
    ind = OxmlElement('w:tblInd'); ind.set(qn('w:w'), '120'); ind.set(qn('w:type'), 'dxa'); tblPr.append(ind)
    for row in table.rows:
        for i, cell in enumerate(row.cells):
            set_width(cell, widths[i]); set_cell_margins(cell); cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER

def font(run, size=11, bold=False, color='000000', name='宋体'):
    run.font.name = name; run._element.rPr.rFonts.set(qn('w:eastAsia'), name); run._element.rPr.rFonts.set(qn('w:ascii'), 'Calibri'); run._element.rPr.rFonts.set(qn('w:hAnsi'), 'Calibri')
    run.font.size = Pt(size); run.bold = bold; run.font.color.rgb = RGBColor.from_string(color)

def add_p(doc, text='', style=None, size=11, bold=False, color='000000', before=0, after=6, align=None):
    p = doc.add_paragraph(style=style)
    pf = p.paragraph_format; pf.space_before = Pt(before); pf.space_after = Pt(after); pf.line_spacing = 1.25
    if align is not None: p.alignment = align
    r = p.add_run(text); font(r, size, bold, color)
    return p

def heading(doc, text, level=1):
    p = doc.add_paragraph(style=f'Heading {level}')
    p.paragraph_format.space_before = Pt({1:18,2:14,3:10}[level]); p.paragraph_format.space_after = Pt({1:10,2:7,3:5}[level]); p.paragraph_format.keep_with_next = True
    r = p.add_run(text); font(r, {1:16,2:13,3:12}[level], True, BLUE if level < 3 else DARK)
    return p

def bullets(doc, items):
    for item in items:
        p = doc.add_paragraph(style='List Bullet')
        p.paragraph_format.space_after = Pt(4); p.paragraph_format.line_spacing = 1.25
        font(p.add_run(item), 11)

def table(doc, headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'; fixed_table(t, widths)
    for i,h in enumerate(headers):
        c=t.rows[0].cells[i]; shade(c, LIGHT); p=c.paragraphs[0]; p.alignment=WD_ALIGN_PARAGRAPH.CENTER; font(p.add_run(h), 10, True, NAVY)
    for row in rows:
        cells=t.add_row().cells
        for i, val in enumerate(row):
            p=cells[i].paragraphs[0]; p.paragraph_format.space_after=Pt(0); font(p.add_run(str(val)), 9.5)
    doc.add_paragraph().paragraph_format.space_after=Pt(2)
    return t

