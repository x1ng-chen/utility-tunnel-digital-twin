static void generate(char frames[NODE_A_TELEMETRY_FRAME_COUNT][NODE_A_TELEMETRY_FRAME_SIZE],
                     uint16_t lengths[NODE_A_TELEMETRY_FRAME_COUNT])
{
  NodeATelemetrySnapshot snapshot;
  uint32_t sequence = 0U;
  build_snapshot(&snapshot);
  NodeATelemetry_FormatAll(&sequence, &snapshot, frames, lengths);
}

/* Emits the header in a fixed layout so regeneration is byte-stable. */
static int emit(FILE *out)
{
  char frames[NODE_A_TELEMETRY_FRAME_COUNT][NODE_A_TELEMETRY_FRAME_SIZE];
  uint16_t lengths[NODE_A_TELEMETRY_FRAME_COUNT] = {0U};
  uint8_t index;

  generate(frames, lengths);

  if (fprintf(out,
              "/* Generated by tests/node_a_telemetry_vectors.c -- do not edit.\n"
              " * These are the exact bytes Node A transmits for one cycle of the\n"
              " * fixture in that generator.  Regenerate with\n"
              " * tests/update_node_a_telemetry_vectors.sh. */\n"
              "#ifndef NODE_A_TELEMETRY_VECTORS_H\n"
              "#define NODE_A_TELEMETRY_VECTORS_H\n\n"
              "#define NODE_A_TELEMETRY_VECTOR_COUNT %uU\n\n"
              "static const char *const kNodeATelemetryVectors[] = {\n",
              (unsigned)NODE_A_TELEMETRY_FRAME_COUNT) < 0) {
    return 0;
  }
  for (index = 0U; index < NODE_A_TELEMETRY_FRAME_COUNT; ++index) {
    uint16_t offset;
    if (fprintf(out, "  \"") < 0) return 0;
    for (offset = 0U; offset < lengths[index]; ++offset) {
      const unsigned char byte = (unsigned char)frames[index][offset];
      if (byte == '"') {
        if (fputs("\\\"", out) < 0) return 0;
      } else if (byte == '\\') {
        if (fputs("\\\\", out) < 0) return 0;
      } else if (byte == '\r') {
        if (fputs("\\r", out) < 0) return 0;
      } else if (byte == '\n') {
        if (fputs("\\n", out) < 0) return 0;
      } else if (fputc((int)byte, out) == EOF) {
        return 0;
      }
    }
    if (fputs("\",\n", out) < 0) return 0;
  }
  return fputs("};\n\n#endif\n", out) >= 0;
}

static int check(const char *path)
{
  char expected[NODE_A_TELEMETRY_FRAME_COUNT][NODE_A_TELEMETRY_FRAME_SIZE];
  char actual[NODE_A_TELEMETRY_FRAME_COUNT][NODE_A_TELEMETRY_FRAME_SIZE];
  uint16_t expected_lengths[NODE_A_TELEMETRY_FRAME_COUNT] = {0U};
  uint16_t actual_lengths[NODE_A_TELEMETRY_FRAME_COUNT] = {0U};
  char line[1024];
  FILE *file = fopen(path, "rb");
  uint8_t index = 0U;
  uint16_t offset = 0U;

  if (file == NULL) {
    (void)fprintf(stderr, "cannot open %s\n", path);
    return 1;
  }
  generate(expected, expected_lengths);
  /* Nothing else parses the generated file, so a light-weight scan for the
   * vector literals is enough to detect drift. */
  while (fgets(line, (int)sizeof(line), file) != NULL) {
    const char *start = strchr(line, '"');
    const char *end;
    if (start == NULL) continue;
    ++start;
    end = strrchr(start, '"');
    if ((end == NULL) || (end <= start)) continue;
    if (index >= NODE_A_TELEMETRY_FRAME_COUNT) break;
    for (offset = 0U; (start + offset) < end; ++offset) {
      char byte = start[offset];
      if (byte != '\\') {
        actual[index][actual_lengths[index]++] = byte;
        continue;
      }
      ++offset;
      switch (start[offset]) {
        case 'r': actual[index][actual_lengths[index]++] = '\r'; break;
        case 'n': actual[index][actual_lengths[index]++] = '\n'; break;
        case '\\': actual[index][actual_lengths[index]++] = '\\'; break;
        case '"': actual[index][actual_lengths[index]++] = '"'; break;
        default: break;
      }
    }
    ++index;
  }
  (void)fclose(file);
  if (index != NODE_A_TELEMETRY_FRAME_COUNT) {
    (void)fprintf(stderr, "vector file has %u frames, expected %u\n",
                  (unsigned)index, (unsigned)NODE_A_TELEMETRY_FRAME_COUNT);
    return 1;
  }
  for (index = 0U; index < NODE_A_TELEMETRY_FRAME_COUNT; ++index) {
    if ((actual_lengths[index] != expected_lengths[index]) ||
        (memcmp(actual[index], expected[index], expected_lengths[index]) != 0)) {
      (void)fprintf(stderr, "frame %u drifted from the committed vector\n",
                    (unsigned)index);
      return 1;
    }
  }
  return 0;
}

int main(int argc, char **argv)
{
  if ((argc == 3) && (strcmp(argv[1], "--check") == 0)) return check(argv[2]);
  if (argc != 1) {
    (void)fprintf(stderr, "usage: %s [--check <path>]\n", argv[0]);
    return 2;
  }
  return emit(stdout) ? 0 : 1;
}
