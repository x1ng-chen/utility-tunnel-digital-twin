/* Emits the exact bytes Node A puts on the wire for one telemetry cycle.
 *
 * The generator drives the same NodeATelemetry_FormatAll the board runs, so
 * the committed header is producer output rather than a hand-written fixture.
 * Rebuild it with tests/update_node_a_telemetry_vectors.sh; the ESP suite then
 * parses these bytes with the real CTRL-02 consumer, which is what keeps the
 * producer and consumer schemas from drifting apart again.
 *
 * Usage: node_a_telemetry_vectors [--check <path>]
 *   (no arguments)  print the header on stdout
 *   --check <path>  compare the generated header with <path>, non-zero on drift
 */
#include "node_a_telemetry.h"

#include <stdio.h>
#include <string.h>

